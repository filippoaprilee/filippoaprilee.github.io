#!/usr/bin/env node
/* Rebuild TurinPipps' single, ordered UI stylesheet from component sources.
 * Usage: node turinpipps/scripts/build-css.cjs
 * QA:    node turinpipps/scripts/build-css.cjs --check
 * No network, API keys, user data or external build dependencies.
 */
"use strict";
const fs=require("node:fs"),path=require("node:path");
const root=path.resolve(__dirname,"..");
const files=[
 "ui-v2.css","experience-v3.css","experience-v4.css","experience-v5.css",
 "experience-v6.css","organize-v7.css","experience-v8.css","trust-v9.css",
 "experience-v10.css","experience-v12.css","experience-v14.css",
 "experience-v15.css","experience-v16.css"
];
let combined=[
 "/* TurinPipps 16.0.2 — unified, ordered stylesheet.",
 " Generated by turinpipps/scripts/build-css.cjs from the original component styles.",
 " Do not edit this generated bundle directly: regenerate when changing source CSS.",
 " One request, consistent cascade ordering on desktop and mobile. */"
].join("\n")+"\n";
for(const filename of files){
 const content=fs.readFileSync(path.join(root,filename),"utf8").trim();
 combined+="\n/* ===== SOURCE "+filename+" ===== */\n"+content+"\n";
}
const output=path.join(root,"styles-v16.css");
if(process.argv.includes("--check")){
 const previous=fs.readFileSync(output,"utf8");
 if(previous!==combined){
  console.error("styles-v16.css is stale. Run: node turinpipps/scripts/build-css.cjs");
  process.exitCode=1;
 }else console.log("CSS bundle verified ("+files.length+" source files).");
}else{
 fs.writeFileSync(output,combined,"utf8");
 console.log("Built styles-v16.css from "+files.length+" files.");
}
