"use strict";
const {test}=require("node:test"),assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const html=read("index.html"),worker=read("sw.js"),css=read("experience-v16.css");
const combined=read("styles-v16.css"),themeJS=read("experience-v12.js");
const release=JSON.parse(read("release.json"));
const sources=[
 "ui-v2.css","experience-v3.css","experience-v4.css","experience-v5.css",
 "experience-v6.css","organize-v7.css","experience-v8.css","trust-v9.css",
 "experience-v10.css","experience-v12.css","experience-v14.css",
 "experience-v15.css","experience-v16.css"
];
function themeToken(mode,key){
 const prefix='html[data-tp-theme="'+mode+'"]{';
 const at=css.indexOf(prefix);assert.ok(at>=0,"missing "+mode+" palette");
 const body=css.slice(at+prefix.length,css.indexOf("}",at));
 const m=body.match(new RegExp("--tp16-"+key+":(#[0-9a-fA-F]{6})"));
 assert.ok(m,"missing "+mode+" --tp16-"+key);return m[1].toLowerCase();
}
function luminance(hex){
 const v=[1,3,5].map(i=>parseInt(hex.slice(i,i+2),16)/255)
 .map(x=>x<=.04045?x/12.92:Math.pow((x+.055)/1.055,2.4));
 return .2126*v[0]+.7152*v[1]+.0722*v[2];
}
function contrast(a,b){
 const x=luminance(a),y=luminance(b);
 return (Math.max(x,y)+.05)/(Math.min(x,y)+.05);
}
test("one ordered CSS resource loads before all feature scripts",()=>{
 const urls=[...html.matchAll(/<link rel="stylesheet" href="\.\/([^"]+)"/g)].map(x=>x[1]);
 assert.deepEqual(urls,["styles-v16.css?v=16.0.2"]);
 assert.ok(html.indexOf('styles-v16.css?v=16.0.2')<html.indexOf('experience-v12.js?v=16.0.0'));
 const cached=[...worker.matchAll(/'\.\/([^']+\.css\?v=[^']+)'/g)].map(x=>x[1]);
 assert.deepEqual(cached,urls);
 assert.match(worker,/turinpipps-shell-v16\.0\.2/);
 assert.equal(release.version,"16.0.2");
});
test("bundle exactly matches all source styles, in cascade order",()=>{
 let expected=[
  "/* TurinPipps 16.0.2 — unified, ordered stylesheet.",
  " Generated by turinpipps/scripts/build-css.cjs from the original component styles.",
  " Do not edit this generated bundle directly: regenerate when changing source CSS.",
  " One request, consistent cascade ordering on desktop and mobile. */"
 ].join("\n")+"\n";
 for(const file of sources)expected+="\n/* ===== SOURCE "+file+" ===== */\n"+read(file).trim()+"\n";
 assert.equal(combined,expected,"regenerate: node turinpipps/scripts/build-css.cjs");
 assert.ok(combined.length<310000,"bundle should remain below 310 KB uncompressed");
 assert.ok(combined.indexOf("SOURCE experience-v16.css")>combined.indexOf("SOURCE experience-v15.css"));
});
test("light and dark contrast pairs exceed 4.5:1 in the consolidated palette",()=>{
 for(const mode of ["light","dark"]){
  for(const [fg,bg] of [
   ["text","bg"],["text","surface"],["text","soft"],["muted","surface"],
   ["muted","soft"],["accent","surface"],["action-ink","action"]
  ]){
   const a=themeToken(mode,fg),b=themeToken(mode,bg),ratio=contrast(a,b);
   assert.ok(ratio>=4.5,mode+": "+fg+" "+a+" against "+bg+" "+b+" -> "+ratio.toFixed(2)+":1");
  }
 }
});
