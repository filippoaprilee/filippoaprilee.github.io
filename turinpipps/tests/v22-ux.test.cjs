"use strict";
const {test}=require("node:test"),assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.join(__dirname,"..");
const read=name=>fs.readFileSync(path.join(root,name),"utf8");
const html=read("index.html"),css=read("experience-v22.css");
const bundle=read("styles-v16.css"),builder=read("scripts/build-css.cjs");
const sw=read("sw.js"),release=JSON.parse(read("release.json"));
const sourceList=["ui-v2.css","experience-v3.css","experience-v4.css","experience-v5.css",
 "experience-v6.css","organize-v7.css","experience-v8.css","trust-v9.css",
 "experience-v10.css","experience-v12.css","experience-v14.css",
 "experience-v15.css","experience-v16.css","experience-v18.css",
 "experience-v19.css","experience-v21.css","experience-v22.css"];
function luminance(hex){
 const v=[1,3,5].map(i=>parseInt(hex.slice(i,i+2),16)/255)
  .map(n=>n<=.04045?n/12.92:((n+.055)/1.055)**2.4);
 return .2126*v[0]+.7152*v[1]+.0722*v[2];
}
function contrast(a,b){
 const x=luminance(a),y=luminance(b);
 return (Math.max(x,y)+.05)/(Math.min(x,y)+.05);
}
function token(mode,name){
 const begin='html[data-tp-theme="'+mode+'"]{',at=css.indexOf(begin);
 assert.ok(at>=0,"palette "+mode);
 const block=css.slice(at,css.indexOf("}",at));
 const found=block.match(new RegExp("--tp16-"+name+":(#[0-9a-f]{6})","i"));
 assert.ok(found,"token "+mode+" "+name);return found[1];
}
test("one compiled stylesheet and versioned PWA cache",()=>{
 assert.deepEqual([...html.matchAll(/<link rel="stylesheet" href="\.\/([^"]+)"/g)].map(x=>x[1]),
  ["styles-v16.css?v=22.0.0"]);
 assert.match(sw,/turinpipps-shell-v22\.0\.0/);
 assert.match(sw,/\.\/styles-v16\.css\?v=22\.0\.0/);
 assert.equal(release.version,"22.0.0");
});
test("generated bundle equals all 17 sources in order",()=>{
 let expected=[
  "/* TurinPipps 22.0.0 — unified, ordered stylesheet.",
  " Generated by turinpipps/scripts/build-css.cjs from the original component styles.",
  " Do not edit this generated bundle directly: regenerate when changing source CSS.",
  " One request, consistent cascade ordering on desktop and mobile. */"
 ].join("\n")+"\n";
 for(const name of sourceList){
  assert.ok(builder.includes('"'+name+'"'),"builder misses "+name);
  expected+="\n/* ===== SOURCE "+name+" ===== */\n"+read(name).trim()+"\n";
 }
 assert.equal(bundle,expected,"rebuild using scripts/build-css.cjs");
});
test("critical light/dark text and action pairs are WCAG AA",()=>{
 for(const mode of ["light","dark"]){
  const groups=[["text","bg"],["text","surface"],["text","soft"],
   ["muted","surface"],["accent","surface"]];
  for(const [a,b] of groups)assert.ok(contrast(token(mode,a),token(mode,b))>=4.5,mode+" "+a+"/"+b);
  const ink=css.match(new RegExp('html\\[data-tp-theme="'+mode+'"\\]\\{[\\s\\S]*?--tp16-action-ink:(#[0-9a-f]{6})',"i"))?.[1];
  assert.ok(ink&&contrast(ink,token(mode,"action"))>=4.5,mode+" action text");
 }
});
test("listing keeps actions and source truth separate",()=>{
 for(const action of ['data-action="save"','data-action="compare"','data-action="visit"',
  'data-action="contact"','data-action="note"','data-action="copy"']){
  assert.ok(html.includes(action),action);
 }
 assert.ok(html.includes("tp22-property-card"));
 assert.ok(html.includes("Dettagli, costi e verifiche"));
 assert.ok(html.includes("Privato secondo la fonte"));
 assert.match(css,/\.tp19-property-row/);
 assert.match(css,/\.tp19-property-details/);
 assert.match(css,/\.tp19-quick-actions/);
});
test("responsive filters, card actions and comparison are retained",()=>{
 assert.match(css,/@media\(max-width:800px\)/);
 assert.match(css,/@media\(max-width:700px\)/);
 assert.match(css,/@media\(max-width:390px\)/);
 const dynamicScreens=read("experience-v5.js")+read("experience-v14.js");
 for(const id of ["view-results","view-compare","view-saved","view-visits",
  "view-settings","view-profile","view-notifications"]){
  assert.ok(html.includes('id="'+id+'"')||dynamicScreens.includes(id),"missing "+id);
 }
 for(const id of ["tp-main-search","tp-filterbar","sort","list","saved-list"]){
  assert.ok(html.includes('id="'+id+'"'),"missing "+id);
 }
});
test("inline JS, service worker and feature scripts remain parseable",()=>{
 assert.doesNotThrow(()=>new vm.Script(sw,{filename:"sw.js"}));
 for(const match of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)){
  if(match[1].trim())assert.doesNotThrow(()=>new vm.Script(match[1]),"inline JS invalid");
 }
});
